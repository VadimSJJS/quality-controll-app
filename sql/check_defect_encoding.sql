SET LINESIZE 200
SET PAGESIZE 50
COLUMN id FORMAT 999
COLUMN name FORMAT A40
COLUMN dump_hex FORMAT A60
SELECT ID_DEFECT_TYPE AS id, DEFECT_NAME AS name, DUMP(DEFECT_NAME, 1016) AS dump_hex
FROM HLP_DEFECT_TYPE
ORDER BY ID_DEFECT_TYPE;
/
SELECT ID_DEFECT_CAUSE AS id, CAUSE_NAME AS name, DUMP(CAUSE_NAME, 1016) AS dump_hex
FROM HLP_DEFECT_CAUSE
WHERE ID_PARENT_CAUSE IS NULL
ORDER BY ID_DEFECT_CAUSE;
/
EXIT;